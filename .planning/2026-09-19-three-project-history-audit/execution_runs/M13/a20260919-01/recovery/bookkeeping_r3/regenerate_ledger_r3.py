def sha256b(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def rb(path: str) -> bytes:
    with open(path, "rb") as handle:
        return handle.read()


def wb(path: str, data: bytes) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(data)


def recompute_digest(files_map: dict) -> str:
    """The documented rule: sha256 over the sorted relative_path + sha256 list."""
    combined = hashlib.sha256()
    for rel in sorted(files_map):
        combined.update(rel.encode("utf-8"))
        combined.update(files_map[rel]["sha256"].encode("ascii"))
    return combined.hexdigest()


def verify_ledger(attempt: str, ledger: dict) -> dict:
    files_map = ledger.get("files", {})
    recomputed = recompute_digest(files_map)
    missing, mismatched = [], []
    for rel, entry in files_map.items():
        path = os.path.join(attempt, *rel.split("/"))
        if not os.path.exists(path):
            missing.append(rel)
            continue
        data = rb(path)
        if sha256b(data) != entry["sha256"] or len(data) != entry["bytes"]:
            mismatched.append(rel)
    return {
        "file_count_declared": ledger.get("file_count"),
        "file_count_in_map": len(files_map),
        "combined_digest_declared": ledger.get("combined_digest_over_sorted_relative_path_and_sha256"),
        "combined_digest_recomputed": recomputed,
        "combined_digest_reproducible": recomputed
        == ledger.get("combined_digest_over_sorted_relative_path_and_sha256"),
        "files_verified_on_disk": len(files_map) - len(missing) - len(mismatched),
        "files_missing_on_disk": missing,
        "files_with_mismatched_hash": mismatched,
        "pycache_entries_listed": [r for r in files_map if "__pycache__" in r],
    }


def patch_generator(apply: bool) -> dict:
    path = os.path.join(ATTEMPT, GEN_REL)
    before = rb(path)
    text = before.decode("utf-8")
    if "F-r3-04 (independent review 2026-09-20)" in text:
        return {"already_patched": True, "sha256_before": sha256b(before), "sha256_after": sha256b(before),
                "bytes_before": len(before), "bytes_after": len(before)}
    if text.count(WALK_OLD) != 1 or text.count(RULE_OLD) != 1 or text.count(SELFCHECK_ANCHOR) != 1:
        raise AssertionError("finalize_hashes.py does not match the expected original revision")
    text = text.replace(WALK_OLD, WALK_NEW)
    text = text.replace(RULE_OLD, RULE_NEW)
    text = text.replace(SELFCHECK_ANCHOR, SELFCHECK_CODE + SELFCHECK_ANCHOR)
    after = text.encode("utf-8")
    if apply:
        wb(path, after)
    return {"already_patched": False, "sha256_before": sha256b(before), "sha256_after": sha256b(after),
            "bytes_before": len(before), "bytes_after": len(after)}


def run_finalize() -> int:
    gen = os.path.join(ATTEMPT, GEN_REL)
    spec = importlib.util.spec_from_file_location("finalize_hashes_%s" % CARD, gen)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    argv = sys.argv
    sys.argv = ["finalize_hashes.py", "--card", CARD, "--attempt", ATTEMPT]
    try:
        return module.main()
    finally:
        sys.argv = argv


