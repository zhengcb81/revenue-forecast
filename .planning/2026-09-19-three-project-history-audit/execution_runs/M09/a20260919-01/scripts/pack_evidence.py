def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_json(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def dump_json(path, doc):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(doc, handle, ensure_ascii=False, indent=1)
        handle.write("\n")


def rel(path, root):
    return os.path.relpath(path, root).replace("\\", "/")


def iter_attempt_files(attempt):
    for dirpath, dirnames, filenames in os.walk(attempt):
        dirnames[:] = [d for d in dirnames if d not in ("venv", "__pycache__")]
        if any(part in rel(dirpath, attempt) for part in SKIP_DIR_PARTS):
            continue
        for name in sorted(filenames):
            yield os.path.join(dirpath, name)


def read_ledger(attempt):
    ledger = {}
    path = os.path.join(attempt, "after", "rc_ledger.txt")
    if not os.path.exists(path):
        return ledger
    with open(path, "r", encoding="ascii", errors="replace") as handle:
        for line in handle:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            unit, _, rc = line.partition("\t")
            ledger[unit.strip()] = int(rc.strip())
    return ledger


def registration_facts(code_root, model_id):
    path = os.path.join(code_root, "model_registry.py")
    with open(path, "r", encoding="utf-8") as handle:
        lines = handle.read().splitlines()
    observed = None
    for number, text in enumerate(lines, start=1):
        if '_spec("%s"' % model_id in text:
            observed = {"line": number, "text": text.strip()[:400]}
            break
    entry = None
    for number, text in enumerate(lines, start=1):
        if text.startswith("def calculate_registered_model("):
            entry = {"line": number, "text": text.strip()}
            break
    return {"registration_line_observed": observed,
            "entry_point_line_observed": entry,
            "file_sha256": sha256_file(path)}


def survey_card(card, companies_root):
    rows = []
    for name, applicable, why in SURVEY_CANDIDATES[card]:
        company_dir = os.path.join(companies_root, name)
        entry = {"company": name, "company_dir": company_dir, "exists": os.path.isdir(company_dir),
                 "candidate_applicable_to_this_card_industry": applicable,
                 "applicability_reason": why, "financial_reports": []}
        reports_root = os.path.join(company_dir, "raw", "financial_reports")
        if os.path.isdir(reports_root):
            for dirpath, dirnames, filenames in os.walk(reports_root):
                for fname in sorted(filenames):
                    if not fname.lower().endswith(".pdf"):
                        continue
                    pdf = os.path.join(dirpath, fname)
                    sidecar = pdf + ".source.json"
                    row = {"pdf_path": pdf, "pdf_relpath": rel(pdf, company_dir),
                           "pdf_bytes": os.path.getsize(pdf),
                           "pdf_sha256": sha256_file(pdf),
                           "sidecar_path": sidecar if os.path.exists(sidecar) else None,
                           "sidecar_content_sha256": None, "sidecar_byte_size": None,
                           "sidecar_retrieved_at": None, "sidecar_provider": None,
                           "sidecar_fiscal_year": None,
                           "local_pdf_matches_sidecar_content_sha256": None,
                           "local_hash_matches_publisher_receipt": None}
                    if os.path.exists(sidecar):
                        try:
                            doc = load_json(sidecar)
                            row["sidecar_content_sha256"] = doc.get("content_sha256")
                            row["sidecar_byte_size"] = doc.get("byte_size")
                            row["sidecar_retrieved_at"] = doc.get("retrieved_at")
                            row["sidecar_provider"] = doc.get("provider")
                            row["sidecar_fiscal_year"] = doc.get("fiscal_year")
                            row["local_pdf_matches_sidecar_content_sha256"] = (
                                doc.get("content_sha256") == row["pdf_sha256"])
                            row["local_hash_matches_publisher_receipt"] = (
                                "VERIFIABLE" if doc.get("content_sha256") == row["pdf_sha256"]
                                else "MISMATCH")
                        except Exception as exc:  # noqa: BLE001
                            row["sidecar_error"] = "%s: %s" % (type(exc).__name__, exc)
                    entry["financial_reports"].append(row)
        rows.append(entry)
    applicable_rows = [r for r in rows if r["candidate_applicable_to_this_card_industry"]
                       and r["financial_reports"]]
    return {
        "card_id": card,
        "survey_kind": "read-only source presence survey (no PDF text was read, no value was extracted)",
        "companies_root": companies_root,
        "candidates": rows,
        "candidates_with_a_local_source_document": [r["company"] for r in rows if r["financial_reports"]],
        "applicable_candidates_with_a_local_source_document": [r["company"] for r in applicable_rows],
        "conclusion": ("a local source document for this card's industry exists and is listed above"
                       if applicable_rows else
                       "no local source document for this card's industry was found in company-wiki; "
                       "the nearest available names are named above with the reason they do not fit"),
        "not_done_here": "per-driver page/table/span extraction and a closed-period revenue "
                         "reconciliation are D-level work owned by I-10-A; they are NOT claimed here",
    }


