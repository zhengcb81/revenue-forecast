    sections.append(
        f"==== REPO {repo} :: {CW_SRC}/{name} ====\n"
        f"==== source card(s): {origin} ====\n"
        f"==== before sha256: {sha(before)}  after sha256: {sha(after)} ====\n"
        + "".join(diff)
        + f"==== hunks: {len(hunks)} ====\n\n")
