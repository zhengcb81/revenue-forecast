    b_lines = before.read_text(encoding="utf-8").splitlines(keepends=True)
    a_lines = after.read_text(encoding="utf-8").splitlines(keepends=True)
    diff = list(difflib.unified_diff(
        b_lines, a_lines,
        fromfile=f"{repo}:{CW_SRC}/{name} (before {sha(before)})",
        tofile=f"GUARD-MERGE/a20260922-01:iso/{name} (after {sha(after)})",
        n=3))
