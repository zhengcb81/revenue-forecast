def load_tree(root: Path) -> dict:
    root = Path(root)
    for name in list(sys.modules):
        if name == "company_wiki" or name.startswith("company_wiki."):
            del sys.modules[name]
    src = str(root / "cw" / "src")
    sys.path[:] = [p for p in sys.path if p != src]
    sys.path.insert(0, src)
    import company_wiki  # noqa: F401  (trivial package init)

    stub = types.ModuleType("company_wiki.source_catalog")
    stub.__path__ = [str(root / "cw" / "src" / "company_wiki" / "source_catalog")]
    sys.modules["company_wiki.source_catalog"] = stub
