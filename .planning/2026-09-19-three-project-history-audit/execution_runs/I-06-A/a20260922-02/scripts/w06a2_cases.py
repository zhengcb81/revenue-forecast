def _table_names(db: Path) -> set[str]:
    with sqlite3.connect(db) as conn:
        return {r[0] for r in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}


def _columns(db: Path, table: str) -> set[str]:
    with sqlite3.connect(db) as conn:
        return {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}


def _demand_row_dump(db: Path, demand_id: str) -> dict:
    with sqlite3.connect(db) as conn:
        conn.row_factory = sqlite3.Row
        row = conn.execute(
            "SELECT * FROM processing_demands WHERE demand_id=?", (demand_id,)
        ).fetchone()
    return {k: row[k] for k in row.keys()}


def _metadata_of(db: Path, document_id: str) -> str:
    with sqlite3.connect(db) as conn:
        return str(conn.execute(
            "SELECT metadata_json FROM documents WHERE document_id=?", (document_id,)
        ).fetchone()[0])


def _iso(epoch: float) -> str:
    from datetime import datetime, timezone

    return datetime.fromtimestamp(epoch, tz=timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


