def child(target: Path, *args: str) -> dict:
    proc = subprocess.run(
        [sys.executable, str(Path(__file__).resolve()), "--target", str(target), "--child", *args],
        capture_output=True,
        text=True,
        timeout=120,
    )
    if proc.returncode != 0:
        raise CaseFailure(f"child failed rc={proc.returncode}: {proc.stderr[-800:]}")
    return json.loads(proc.stdout)


