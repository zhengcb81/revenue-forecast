def run_child(target: str, argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("op", choices=["register", "query", "claim"])
    parser.add_argument("--db", required=True)
    parser.add_argument("--spec")
    parser.add_argument("--demand-id")
    parser.add_argument("--owner", default="child-worker")
    parser.add_argument("--lease", type=float, default=30.0)
    parser.add_argument("--now", type=float, default=100.0)
    args = parser.parse_args(argv)
    t = load_tree(Path(target))
    dstore = t["pd"].CatalogDemandStore(Path(args.db))
    if args.op == "register":
        spec = json.loads(Path(args.spec).read_text(encoding="utf-8"))
        block = t["pd"].register_before_block(dstore, spec, security_verdict=BLOCK_VERDICT)
        out = {
            "demand_id": block.demand.demand_id if block.demand else None,
            "clause": block.clause,
        }
    elif args.op == "query":
        rows = dstore.list()
        out = {
            "count": len(rows),
            "demands": [
                {
                    "demand_id": r.demand_id,
                    "status": r.status,
                    "source_sha256": r.source_sha256,
                    "review_policy": r.review_policy,
                    "request_sha256": r.request_sha256,
                    "next_action": r.next_action,
                }
                for r in rows
            ],
        }
    else:
        try:
            row = dstore.claim(demand_id=args.demand_id, owner=args.owner,
                               lease_seconds=args.lease, now=args.now)
            out = {"ok": True, "status": row.status, "lease_owner": row.lease_owner}
        except t["pd"].DemandQueueError as exc:
            out = {"ok": False, "error": f"{type(exc).__name__}: {exc}"}
    # Self-evidence for the cross-process claim (review finding 3): every
    # child reports its own pid and literal argv in its output envelope.
    out["pid"] = os.getpid()
    out["argv"] = list(sys.argv)
    sys.stdout.write(json.dumps(out, ensure_ascii=False))
    return 0


# --------------------------------------------------------------------------
# main
# --------------------------------------------------------------------------
def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", required=True)
    parser.add_argument("--out")
    parser.add_argument("--child", dest="child_args", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    if args.child_args:
        return run_child(args.target, args.child_args)
    target = Path(args.target)
    results = []
    for case_id, fn in CASES:
        started = time.time()
        try:
            t = load_tree(target)
            measurement = fn(t) or {}
            results.append({
                "case": case_id,
                "result": "PASS",
                "measurement": measurement,
                "seconds": round(time.time() - started, 3),
            })
        except BaseException as exc:  # noqa: BLE001 - evidence collection
            results.append({
                "case": case_id,
                "result": "FAIL",
                "error": f"{type(exc).__name__}: {exc}",
                "traceback": traceback.format_exc()[-1500:],
                "seconds": round(time.time() - started, 3),
            })
    summary = {
        "target": str(target),
        "passed": sum(1 for r in results if r["result"] == "PASS"),
        "failed": sum(1 for r in results if r["result"] == "FAIL"),
        "results": results,
    }
    text = json.dumps(summary, ensure_ascii=False, indent=2)
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
    for r in results:
        line = f"{r['case']:12s} {r['result']}"
        if r["result"] == "FAIL":
            line += f"  {r['error'][:140]}"
        print(line)
    print(f"== {summary['passed']} passed / {summary['failed']} failed  ({target})")
    return 0 if summary["failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
